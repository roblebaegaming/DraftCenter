-- Reviewed, source-attributed competitive tournament observations.
-- No player names, handles, countries, or account identifiers are stored.

create table public.competitive_tournaments (
  id bigint generated by default as identity primary key,
  format_id text not null references public.competitive_formats(id) on delete restrict,
  source_name text not null check (char_length(source_name) between 2 and 80),
  source_event_id text not null check (source_event_id ~ '^[a-zA-Z0-9_-]{4,100}$'),
  source_url text not null check (source_url ~ '^https://'),
  name text not null check (char_length(name) between 2 and 200),
  event_date date not null,
  event_kind text not null check (event_kind in ('online-community', 'official-major', 'grassroots-major', 'other')),
  player_count integer not null check (player_count > 1),
  team_count integer not null check (team_count between 1 and player_count),
  top_cut_size integer check (top_cut_size is null or top_cut_size between 2 and player_count),
  team_sheet_coverage numeric(6,3) not null check (team_sheet_coverage between 0 and 100),
  is_official boolean not null default false,
  source_sha256 text not null check (source_sha256 ~ '^[a-f0-9]{64}$'),
  imported_at timestamptz not null default now(),
  unique (source_name, source_event_id)
);

create table public.competitive_tournament_teams (
  id bigint generated by default as identity primary key,
  tournament_id bigint not null references public.competitive_tournaments(id) on delete cascade,
  source_entry_key text not null check (source_entry_key ~ '^placement-[0-9]{1,6}$'),
  placement integer not null check (placement > 0),
  wins integer not null check (wins >= 0),
  losses integer not null check (losses >= 0),
  ties integer not null check (ties >= 0),
  made_top_cut boolean,
  is_finalist boolean not null,
  is_champion boolean not null,
  roster_size smallint not null check (roster_size between 1 and 12),
  unique (tournament_id, source_entry_key),
  unique (tournament_id, placement),
  check (not is_champion or placement = 1),
  check (not is_finalist or placement <= 2)
);

create table public.competitive_tournament_team_members (
  team_id bigint not null references public.competitive_tournament_teams(id) on delete cascade,
  slot smallint not null check (slot between 1 and 12),
  pokemon_key text not null check (pokemon_key ~ '^[a-z0-9-]{1,100}$'),
  pokemon_name text not null check (char_length(pokemon_name) between 1 and 120),
  primary key (team_id, slot),
  unique (team_id, pokemon_key)
);

create index competitive_tournaments_format_date_idx on public.competitive_tournaments (format_id, event_date desc);
create index competitive_tournament_members_key_idx on public.competitive_tournament_team_members (pokemon_key, team_id);
create index competitive_tournament_teams_event_idx on public.competitive_tournament_teams (tournament_id, placement);

alter table public.competitive_tournaments enable row level security;
alter table public.competitive_tournament_teams enable row level security;
alter table public.competitive_tournament_team_members enable row level security;

revoke all on public.competitive_tournaments from public, anon, authenticated;
revoke all on public.competitive_tournament_teams from public, anon, authenticated;
revoke all on public.competitive_tournament_team_members from public, anon, authenticated;
grant all on public.competitive_tournaments to service_role;
grant all on public.competitive_tournament_teams to service_role;
grant all on public.competitive_tournament_team_members to service_role;
revoke all on sequence public.competitive_tournaments_id_seq from public, anon, authenticated;
revoke all on sequence public.competitive_tournament_teams_id_seq from public, anon, authenticated;
grant usage, select on sequence public.competitive_tournaments_id_seq to service_role;
grant usage, select on sequence public.competitive_tournament_teams_id_seq to service_role;

create or replace function public.get_public_pokemon_tournament_profile(p_pokemon_key text)
returns jsonb
language sql
stable
security definer
set search_path = public, pg_temp
as $$
  with requested as (
    select lower(regexp_replace(coalesce(p_pokemon_key, ''), '[^a-zA-Z0-9]+', '-', 'g')) as pokemon_key
  ), pokemon_teams as (
    select
      e.id as tournament_id, e.format_id, e.name as event_name, e.event_date,
      e.event_kind, e.player_count, e.team_count, e.top_cut_size,
      e.team_sheet_coverage, e.source_name, e.source_url,
      t.id as team_id, t.placement, t.wins as match_wins, t.losses as match_losses,
      t.ties as match_ties, t.made_top_cut, t.is_finalist, t.is_champion
    from requested r
    join public.competitive_tournament_team_members m on m.pokemon_key = r.pokemon_key
    join public.competitive_tournament_teams t on t.id = m.team_id
    join public.competitive_tournaments e on e.id = t.tournament_id
  ), relevant_formats as (
    select format_id from pokemon_teams group by format_id order by max(event_date) desc limit 6
  ), format_denominators as (
    select e.format_id, count(*) as tournaments, sum(e.team_count) as imported_teams,
      min(e.event_date) as period_start, max(e.event_date) as period_end
    from public.competitive_tournaments e
    join relevant_formats rf on rf.format_id = e.format_id
    group by e.format_id
  ), rollups as (
    select
      f.id as format_id, f.name as format_name, f.regulation_id,
      f.battle_style, f.ruleset_family,
      d.tournaments, d.imported_teams, d.period_start, d.period_end,
      count(*) as team_appearances,
      count(distinct pt.tournament_id) as event_appearances,
      count(*) filter (where pt.made_top_cut) as top_cuts,
      count(*) filter (where pt.is_finalist) as finals,
      count(*) filter (where pt.is_champion) as wins,
      sum(pt.match_wins) as match_wins, sum(pt.match_losses) as match_losses, sum(pt.match_ties) as match_ties,
      round(100.0 * count(*) / nullif(d.imported_teams, 0), 2) as field_usage,
      round(100.0 * count(*) filter (where pt.made_top_cut) / nullif(count(*) filter (where pt.made_top_cut is not null), 0), 2) as top_cut_conversion,
      round(100.0 * count(*) filter (where pt.is_finalist) / nullif(count(*), 0), 2) as finals_conversion,
      round(100.0 * count(*) filter (where pt.is_champion) / nullif(count(*), 0), 2) as win_conversion,
      round(100.0 * sum(pt.match_wins) / nullif(sum(pt.match_wins + pt.match_losses + pt.match_ties), 0), 2) as match_win_rate
    from pokemon_teams pt
    join format_denominators d on d.format_id = pt.format_id
    join public.competitive_formats f on f.id = pt.format_id
    group by f.id, f.name, f.regulation_id, f.battle_style, f.ruleset_family,
      d.tournaments, d.imported_teams, d.period_start, d.period_end
  ), best_event_results as (
    select distinct on (format_id, tournament_id) *
    from pokemon_teams
    where placement <= 16
    order by format_id, tournament_id, placement
  ), recent_results as (
    select r.format_id, jsonb_agg(jsonb_build_object(
      'event_name', r.event_name, 'event_date', r.event_date,
      'event_kind', r.event_kind, 'placement', r.placement,
      'player_count', r.player_count, 'team_sheet_coverage', r.team_sheet_coverage,
      'source_name', r.source_name, 'source_url', r.source_url
    ) order by r.event_date desc, r.placement asc) as results
    from (
      select pt.*, row_number() over (partition by pt.format_id order by pt.event_date desc, pt.placement asc) as row_number
      from best_event_results pt
    ) r
    where r.row_number <= 5
    group by r.format_id
  ), teammate_counts as (
    select pt.format_id, teammate.pokemon_key, teammate.pokemon_name, count(*) as teams,
      row_number() over (partition by pt.format_id order by count(*) desc, teammate.pokemon_name) as row_number
    from pokemon_teams pt
    join public.competitive_tournament_team_members teammate on teammate.team_id = pt.team_id
    join requested r on teammate.pokemon_key <> r.pokemon_key
    group by pt.format_id, teammate.pokemon_key, teammate.pokemon_name
  ), teammates as (
    select format_id, jsonb_agg(jsonb_build_object(
      'pokemon_key', pokemon_key, 'pokemon_name', pokemon_name, 'teams', teams
    ) order by teams desc, pokemon_name) as teammates
    from teammate_counts where row_number <= 8 group by format_id
  )
  select coalesce(jsonb_agg(
    to_jsonb(rollups) || jsonb_build_object(
      'recent_results', coalesce(recent_results.results, '[]'::jsonb),
      'teammates', coalesce(teammates.teammates, '[]'::jsonb)
    ) order by rollups.period_end desc, rollups.format_name
  ), '[]'::jsonb)
  from rollups
  left join recent_results using (format_id)
  left join teammates using (format_id)
  ;
$$;

revoke execute on function public.get_public_pokemon_tournament_profile(text) from public;
grant execute on function public.get_public_pokemon_tournament_profile(text) to anon, authenticated;
