import fs from "node:fs";
import path from "node:path";

const SOURCE_URL = "https://victoryroad.pro/2026-worlds-invites/";
const CHECKED_AT = "2026-08-10";
const OUTPUT_PATH = path.resolve("src/data/worlds-2026-vgc-masters.json");
const MIGRATION_PATH = path.resolve("supabase/370-seed-worlds-2026-vgc-masters-roster.sql");
const buildInitialSeed = process.argv.includes("--initial-seed");
const EXPECTED_COUNTS = new Map([
  ["North America", 98],
  ["Europe", 93],
  ["Latin America", 68],
  ["Oceania", 23],
  ["Middle East & South Africa", 6],
  ["Japan", 66],
  ["South Korea", 16],
  ["Asia-Pacific", 68],
]);
const YOUTH_DIVISION_MARKER = /(?:Junior|Senior) Division|Worlds\s*\((?:JR|SR)\)/i;

const decodeEntities = (value) => value.replace(
  /&(amp|quot|apos|nbsp|#\d+|#x[0-9a-f]+);/gi,
  (entity, token) => {
    const normalized = token.toLowerCase();
    if (normalized === "amp") return "&";
    if (normalized === "quot") return '"';
    if (normalized === "apos") return "'";
    if (normalized === "nbsp") return " ";
    if (normalized.startsWith("#x")) return String.fromCodePoint(Number.parseInt(normalized.slice(2), 16));
    return String.fromCodePoint(Number(normalized.slice(1)));
  },
);

const textContent = (value) => decodeEntities(value)
  .replace(/<br\s*\/?>/gi, " / ")
  .replace(/<[^>]+>/g, " ")
  .replace(/\s*\/\s*\/\s*/g, " / ")
  .replace(/\s+/g, " ")
  .trim();

const slugify = (value) => value
  .normalize("NFKD")
  .replace(/[\u0300-\u036f]/g, "")
  .toLowerCase()
  .replace(/[^a-z0-9]+/g, "-")
  .replace(/^-|-$/g, "");

function sectionTable(html, heading) {
  const headingNeedle = `>${heading.replaceAll("&", "&amp;")}</div>`;
  const headingIndex = html.indexOf(headingNeedle);
  if (headingIndex < 0) throw new Error(`Could not find ${heading} roster heading.`);
  const headingEnd = html.indexOf("</h2>", headingIndex);
  if (headingEnd < 0) throw new Error(`Could not find the end of the ${heading} roster heading.`);
  const tail = html.slice(headingEnd + 5);
  const tableMatch = /<table[^>]*>([\s\S]*?)<\/table>/i.exec(tail);
  if (!tableMatch) throw new Error(`Could not find ${heading} roster table.`);
  return tableMatch[1];
}

function parseRoster(html) {
  const competitors = [];
  const usedSlugs = new Set();

  for (const [region, expectedCount] of EXPECTED_COUNTS) {
    const table = sectionTable(html, region);
    const rows = [...table.matchAll(/<tr[^>]*>([\s\S]*?)<\/tr>/gi)].slice(1);
    if (rows.length !== expectedCount) {
      throw new Error(`${region} has ${rows.length} rows; expected ${expectedCount}. Review the source before updating.`);
    }

    for (const [index, rowMatch] of rows.entries()) {
      const cells = [...rowMatch[1].matchAll(/<td[^>]*>([\s\S]*?)<\/td>/gi)].map((match) => match[1]);
      if (cells.length < 3) throw new Error(`Unexpected ${region} row ${index + 1}.`);
      const countryMatch = /<img[^>]+alt=["']([^"']+)["']/i.exec(cells[2]);
      const name = textContent(cells[2]);
      const countryCode = countryMatch?.[1]?.trim().toUpperCase();
      const qualification = textContent(cells[1]);
      const resultSummary = textContent(cells[3] || "");
      if (!name || !countryCode) throw new Error(`Missing player or country in ${region} row ${index + 1}.`);
      if (YOUTH_DIVISION_MARKER.test(`${qualification} ${resultSummary}`)) {
        throw new Error(`${name} is marked as a Junior or Senior competitor. This pool is Masters-only.`);
      }

      let slug = slugify(name);
      if (usedSlugs.has(slug)) slug = `${slug}-${countryCode.toLowerCase()}`;
      if (usedSlugs.has(slug)) throw new Error(`Duplicate competitor slug: ${slug}`);
      usedSlugs.add(slug);

      competitors.push({
        slug,
        name,
        countryCode,
        region,
        division: "Masters",
        qualification,
      });
    }
  }

  if (competitors.length !== 438) throw new Error(`Expected 438 invitees; found ${competitors.length}.`);
  return competitors;
}

function sqlLiteral(value) {
  return `'${String(value).replaceAll("'", "''")}'`;
}

function rosterMigration(competitors) {
  const rows = competitors.map((competitor, index) => `  (${[
    sqlLiteral("2026-vgc-masters"),
    sqlLiteral(competitor.slug),
    sqlLiteral(competitor.name),
    sqlLiteral(competitor.countryCode),
    sqlLiteral(competitor.region),
    sqlLiteral(competitor.qualification),
    index + 1,
    sqlLiteral(SOURCE_URL),
    sqlLiteral(CHECKED_AT),
  ].join(", ")})`).join(",\n");

  return `-- Generated by scripts/build-worlds-2026-roster.mjs from the cited public invite tracker.\n` +
    `-- This is a forward-only seed. Publish later roster changes in a new migration.\n\n` +
    `insert into public.worlds_pick_competitors (\n` +
    `  event_id, slug, display_name, country_code, qualification_region, qualification_path,\n` +
    `  source_order, source_url, source_checked_at\n` +
    `) values\n${rows}\n` +
    `on conflict (event_id, slug) do nothing;\n`;
}

const response = await fetch(SOURCE_URL, { headers: { "user-agent": "DraftCenter roster verifier/1.0" } });
if (!response.ok) throw new Error(`Roster source returned ${response.status}.`);
const competitors = parseRoster(await response.text());
const payload = {
  eventId: "2026-vgc-masters",
  division: "Masters",
  ageScope: "official-masters-division-not-age-verified",
  sourceUrl: SOURCE_URL,
  sourceCheckedAt: CHECKED_AT,
  status: "invite-earned-not-attendance-confirmed",
  competitors,
};

fs.mkdirSync(path.dirname(OUTPUT_PATH), { recursive: true });
fs.writeFileSync(OUTPUT_PATH, `${JSON.stringify(payload, null, 2)}\n`, "utf8");
if (buildInitialSeed) {
  if (fs.existsSync(MIGRATION_PATH)) {
    throw new Error(`${path.relative(process.cwd(), MIGRATION_PATH)} already exists. Never overwrite a forward-only migration.`);
  }
  fs.writeFileSync(MIGRATION_PATH, rosterMigration(competitors), "utf8");
}
console.log(`Wrote ${competitors.length} invitees to ${path.relative(process.cwd(), OUTPUT_PATH)}${buildInitialSeed ? ` and ${path.relative(process.cwd(), MIGRATION_PATH)}` : "; the existing seed migration was not changed"}.`);
